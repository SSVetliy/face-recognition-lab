SUPPORTED_IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png", ".bmp", ".webp")

# Ожидаемая длина эмбеддинга у ArcFace. Используем для проверки,
# что модель выдала именно тот формат, который мы ждём.
