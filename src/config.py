# ─────────────────────────────────────────────────────────────
# Пороги расстояний (для сравнения эмбеддингов)
# ─────────────────────────────────────────────────────────────
# Insightface нормализует эмбеддинги (L2), поэтому косинусное
# расстояние = 1 - cosine_similarity. Диапазон [0..2], но
# на практике для лиц интересен [0..1].
#
# Эмпирические ориентиры для ArcFace / buffalo:
#   < 0.4  — почти наверняка один человек
#   0.4..0.6 — серая зона (похожие люди, родственники)
#   > 0.6  — почти наверняка разные люди
#
# Эти числа будем уточнять на Этапе 5. Пока — стартовые.
SAME_PERSON_THRESHOLD = 0.40
DIFFERENT_PERSON_THRESHOLD = 0.60